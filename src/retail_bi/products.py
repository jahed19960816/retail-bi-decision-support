"""Keyword-based product families.

The source data has no product category, so families are derived from the
product description with transparent, ordered keyword rules (first match wins).
This is good enough for portfolio-level category KPIs; a real business would
use its product master instead.
"""

import numpy as np
import pandas as pd

FAMILY_RULES = [
    ("Christmas & Seasonal", r"CHRISTMAS|XMAS|ADVENT|EASTER|HALLOWEEN|SANTA|REINDEER|SNOWFLAKE|BAUBLE|NATIVITY"),
    ("Candles & Lighting", r"CANDLE|T-LIGHT|TEALIGHT|LANTERN|\bLIGHTS?\b|LAMP|INCENSE|NIGHTLIGHT"),
    ("Kitchen & Dining", r"\bMUGS?\b|\bCUPS?\b|PLATE|BOWL|\bTEA\b|TEACUP|TEAPOT|COFFEE|CAKE|BAKING|KITCHEN|NAPKIN|SPOON|\bJUG\b|GLASS|LUNCH|BOTTLE|TRAY|PANTRY|APRON|\bEGG|JAM|CUTLERY|COASTER|SAUCER|OVEN GLOVE|CHOPSTICK|BREAD BIN|BUTTER DISH|COOKIE CUTTER|DOILIES|CAKESTAND|FOOD CONTAINER"),
    ("Bags & Storage", r"\bBAGS?\b|\bBOX(?:ES)?\b|\bTINS?\b|STORAGE|BASKET|\bCASE\b|\bJARS?\b|HOLDER|DRAWER|HAMPER|SHOPPER|TOTE|CRATE|CABINET|MINI CASES|TRINKET POT|PIGGY BANK"),
    ("Stationery & Gift Wrap", r"\bCARDS?\b|WRAP|PAPER|NOTEBOOK|\bPENS?\b|PENCIL|STICKER|\bTAPE\b|ENVELOPE|RIBBON|\bGIFT\b|CRAFT|DIARY|CALENDAR|NOTE ?PAD|ERASER|RULER|JOURNAL|STAMP"),
    ("Toys & Kids", r"\bTOYS?\b|\bGAMES?\b|PLAYHOUSE|DOLL|CHILDREN|CHILDS|\bKIDS?\b|SPACEBOY|PUZZLE|SKITTLES|DOMINO|JIGSAW|TEDDY|BALLOON|CRAYON|COLOURING|SPINNING TOP|SKIPPING|PAINT SET|MODELLING|KNITTING|SEWING KIT|BINGO|SNAKES|LADDERS|GLIDERS|BUILDING BLOCK|SOMBRERO|LEIS|SILK FAN"),
    ("Jewellery & Accessories", r"NECKLACE|BRACELET|EARRING|\bRING\b|\bHAIR|BROOCH|\bCHARM|PURSE|UMBRELLA|PARASOL|GLOVES|SCARF|WALLET|SUNGLASSES|KEY ?RING|HAND WARMER|BEADS?|LIP GLOSS|CLIPS|PONCHO|TISSUES"),
    ("Garden & Outdoor", r"GARDEN|PLANT|FLOWER POT|BIRD ?HOUSE|BIRD FEEDER|BIRD TABLE|WATERING|PICNIC|\bSEED|POTTING|HERB|DOVECOTE|WINDMILL|OUTDOOR|HAMMOCK"),
    ("Home Decor", r"\bSIGN\b|FRAME|CUSHION|CLOCK|MIRROR|DECORATION|HANGING|HEART|WREATH|DOORMAT|VASE|ORNAMENT|PLAQUE|BUNTING|GARLAND|DOOR ?STOP|HOOK|CHANDELIER|WALL ART|BLANKET|THROW|QUILT|HOT WATER BOTTLE|DOORKNOB|SOAP|TOWEL|PICTURE|LETTER|CHALKBOARD|FLAG|PEG|SCULPTURE|STAND|BOARD|DOOR MAT|COAT RACK|FLYING DUCKS|WICKER|SLEIGH BELLS|METAL PEARS"),
]
OTHER = "Other"


def product_family(descriptions: pd.Series) -> pd.Series:
    text = descriptions.fillna("").str.upper()
    conditions = [text.str.contains(pattern, regex=True) for _, pattern in FAMILY_RULES]
    families = [name for name, _ in FAMILY_RULES]
    return pd.Series(np.select(conditions, families, default=OTHER), index=descriptions.index)
